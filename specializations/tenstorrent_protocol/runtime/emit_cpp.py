def emit_kernel() -> str:
    return KERNEL_TEMPLATE.format(**OPCODES)


def emit_input_gen() -> str:
    return INPUT_GEN_TEMPLATE


def emit_host(task: protocol.Task, program) -> str:
    program = tuple(program)
    if 4 + 3 * len(program) > 341:
        raise ValueError('program exceeds pinned Metalium 341-word runtime argument capacity (112 instructions)')
    expected_body = _cpp_uint_list(list(task.expected))
    program_body = _cpp_uint_list(encode_program(program))
    return HOST_TEMPLATE.format(
        input_pages=task.input_pages,
        output_pages=len(task.expected),
        slots=task.slots,
        page_bytes=task.page_bytes,
        expected_body=expected_body,
        n_instr=len(tuple(program)),
        program_body=program_body,
    )


def emit_cmake() -> str:
    return CMAKE_TEMPLATE.format()


def emit_bundle(task: protocol.Task, proposal: protocol.Proposal) -> dict[str, str]:
    """Relative path -> file content for a complete buildable bundle."""
    return {
        "host_main.cpp": emit_host(task, proposal.program),
        "input_gen.hpp": emit_input_gen(),
        "kernels/dm_slot_copy.cpp": emit_kernel(),
        "CMakeLists.txt": emit_cmake(),
        "task.json": task_to_dict_json(task),
        "proposal.json": proposal_to_dict_json(proposal),
    }


def _task_to_dict(task: protocol.Task) -> dict:
    return {
        "id": task.id,
        "input_pages": task.input_pages,
        "expected": list(task.expected),
        "slots": task.slots,
        "page_bytes": task.page_bytes,
    }


task_to_dict = _task_to_dict


def _proposal_to_dict(proposal: protocol.Proposal) -> dict:
    return {
        "program": [op_to_dict(op) for op in proposal.program],
        "rationale": proposal.rationale,
    }


proposal_to_dict = _proposal_to_dict


def _json_dump(obj: dict) -> str:
    import json

    return json.dumps(obj, indent=2) + "\n"


def task_to_dict_json(task: protocol.Task) -> str:
    return _json_dump(_task_to_dict(task))


def proposal_to_dict_json(proposal: protocol.Proposal) -> str:
    return _json_dump(_proposal_to_dict(proposal))


